#!/bin/sh

# Usage: ./get_vscode_node_modules.sh <vscode version>
# Example: ./get_vscode_node_modules.sh 1.97.1

_startdir=$PWD
. "$_startdir/kaiju.conf"
. "$_startdir/include/kaiju.sh"

# func
# die [what]
die () {
    _errc=$?
    if [ -n "$1" ]; then
        echo ">>> $1 failed ($_errc)"
    fi
    exit $_errc
}

if [ "$1" != "" ]; then
    _ver="$1"
else
    echo "Error: not set vscode version"
    echo "Usage: ./get_vscode_node_modules.sh <vscode version>"
	exit 1
fi

getver() {
    grep "^$_ver" vscode.versions|cut -d: -f"$1"
}

_rs_ver=$(getver 3)
_ccli_ver=$(getver 4)
_csdk_ver=$(getver 5)
_op_ver=$(getver 6)


# get sources
if [ ! -f "$tools_workdir/vscode-${_ver}-download_done" ]; then
    cd "$tools_workdir" || die
    echo "Download distfile..."
    if [ ! -f "$distfiles/vscode-${_ver}.tar.gz" ]; then
         curl -L "https://github.com/microsoft/vscode/archive/${_ver}.tar.gz" \
              -o "$distfiles/vscode-${_ver}.tar.gz" \
              || die "curl vscode"
    fi
    cd "$_startdir" || die
    touch "$tools_workdir/vscode-${_ver}-download_done"
fi

# extract tarballs
if [ ! -f "$tools_workdir/vscode-${_ver}-extract_done" ]; then
    cd "$tools_workdir" || die
    echo "Extract distfiles..."
    if [ -d "vscode-netbsd-${_ver}" ]; then
        rm -rf "vscode-netbsd-${_ver}" || die
    fi
    mkdir -p "vscode-netbsd-${_ver}/vscode-node_modules-${_ver}" || die
    tar -xzf "$distfiles/vscode-${_ver}.tar.gz" --strip-components=1 -C "vscode-netbsd-${_ver}" || die "extract vscode"

    fetch_freebsd_ports
    if [ -d "freebsd-ports/editors/vscode/files" ]; then
        p_dir="../freebsd-ports/editors/vscode/files"
    else
        echo "Error: not found freebsd ports tree"
        exit 1
    fi
    cd "vscode-netbsd-${_ver}" || die
    for _patch in "$p_dir"/patch-package.json \
                  "$p_dir"/patch-remote_package.json ; do
        if [ -e "$_patch" ]; then
            patch -Np0 -i "$_patch"
        fi
    done

    cd "$_startdir" || die
    touch "$tools_workdir/vscode-${_ver}-extract_done"
fi

# get node modules
if [ ! -f "$tools_workdir/vscode-${_ver}-getnode_done" ]; then
    cd "$tools_workdir/vscode-netbsd-${_ver}" || die
    _bd=$PWD
    _cache="$_bd/vscode-node_modules-${_ver}"
    rm -rf "$_cache"

    for _subdir in . $(node --input-type=module -e "console.log(JSON.stringify((await import('./build/npm/dirs.ts')).dirs))" | jq -r '.[]'); do
        cd "$_subdir" || die
        npm install --ignore-scripts --no-progress --no-audit --no-fund --no-update-notifier --cache "$_cache" || die "npm install $_subdir"
        if [ -d node_modules ]; then
            rm -rf node_modules
        fi
        cd "$_bd" || die
    done

    for _arch in arm64 x64; do
        for _cnpm in "https://registry.npmjs.org/@vscode/os-proxy-resolver-linux-${_arch}-gnu/-/os-proxy-resolver-linux-${_arch}-gnu-${_op_ver}.tgz" \
                     "https://registry.npmjs.org/@github/copilot-linux-${_arch}/-/copilot-linux-${_arch}-${_ccli_ver}.tgz" \
                     "https://registry.npmjs.org/@github/copilot-sdk-linux-${_arch}/-/copilot-sdk-linux-${_arch}-${_csdk_ver}.tgz" ; do
            _tnpm=$(echo "$_cnpm" | sed -n 's|.*/-/\(.*\)|\1|p')
            curl -L "$_cnpm" -o "$_bd/vscode-node_modules-${_ver}/$_tnpm" || die "curl vscode"
        done
    done

    if [ -f "../vscode-node_modules-${_ver}.tar.gz" ]; then
        rm -f "../vscode-node_modules-${_ver}.tar.gz" || die
    fi
    tar -czf "../vscode-node_modules-${_ver}.tar.gz" "vscode-node_modules-${_ver}" || die "create tarball"
    cd "$_startdir" || die
    touch "$tools_workdir/vscode-${_ver}-getnode_done"
fi

# clean
if [ -f "$tools_workdir/vscode-${_ver}-getnode_done" ]; then
    rm "$tools_workdir/vscode-${_ver}-download_done"
    rm "$tools_workdir/vscode-${_ver}-extract_done"
    rm "$tools_workdir/vscode-${_ver}-getnode_done"
fi

exit 0

